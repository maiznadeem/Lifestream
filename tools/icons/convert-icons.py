"""Converts the direction A outline icons (24 x 24 SVG symbols, 1.5 px round strokes) into WPF path data for Controls/IconData.cs.

Each symbol has stroked parts and optional "duo" parts (filled with 14 % of the icon colour in the selected state). Circles and rounded
rectangles are turned into paths, and every path is normalised through fontTools' SVG path parser into absolute M/L/C/Z commands, which
WPF's path mini-language reads without surprises (SVG shorthand such as implicit line-tos and packed arc flags is gone).

Usage: python tools/icons/convert-icons.py <symbols.html> > src/Lifestream.Desktop/Controls/IconData.cs
The symbols file is the <svg><defs> block of the design mock (scratch/design/_tools/p2.html).
"""

import re
import sys

from fontTools.pens.basePen import BasePen
from fontTools.svgLib.path import parse_path


class WpfPen(BasePen):
    def __init__(self):
        super().__init__(None)
        self.parts = []

    def _moveTo(self, p):
        self.parts.append(f"M{fmt(p)}")

    def _lineTo(self, p):
        self.parts.append(f"L{fmt(p)}")

    def _curveToOne(self, p1, p2, p3):
        self.parts.append(f"C{fmt(p1)} {fmt(p2)} {fmt(p3)}")

    def _qCurveToOne(self, p1, p2):
        self.parts.append(f"Q{fmt(p1)} {fmt(p2)}")

    def _closePath(self):
        self.parts.append("Z")

    def _endPath(self):
        pass


def num(v):
    s = f"{v:.3f}".rstrip("0").rstrip(".")
    return "0" if s in ("-0", "") else s


def fmt(p):
    return f"{num(p[0])},{num(p[1])}"


def attr(tag, name, default=None):
    m = re.search(rf'\b{name}="([^"]*)"', tag)
    return m.group(1) if m else default


def shape_to_path(tag):
    kind = re.match(r"<(\w+)", tag).group(1)
    if kind == "path":
        return attr(tag, "d")
    if kind == "circle":
        cx, cy, r = (float(attr(tag, k)) for k in ("cx", "cy", "r"))
        return f"M{cx - r} {cy}a{r} {r} 0 1 0 {2 * r} 0a{r} {r} 0 1 0 {-2 * r} 0z"
    if kind == "rect":
        x, y, w, h = (float(attr(tag, k, "0")) for k in ("x", "y", "width", "height"))
        rx = float(attr(tag, "rx", "0"))
        if rx == 0:
            return f"M{x} {y}h{w}v{h}h{-w}z"
        return (f"M{x + rx} {y}h{w - 2 * rx}a{rx} {rx} 0 0 1 {rx} {rx}v{h - 2 * rx}a{rx} {rx} 0 0 1 {-rx} {rx}"
                f"h{-(w - 2 * rx)}a{rx} {rx} 0 0 1 {-rx} {-rx}v{-(h - 2 * rx)}a{rx} {rx} 0 0 1 {rx} {-rx}z")
    raise ValueError(kind)


def to_wpf(d):
    pen = WpfPen()
    parse_path(d, pen)
    return " ".join(pen.parts)


def pascal(name):
    return "".join(part.capitalize() for part in re.split(r"[-_]", name))


def main(path):
    html = open(path, encoding="utf-8").read()
    rows = []
    for m in re.finditer(r'<symbol id="i-([\w-]+)"[^>]*>(.*?)</symbol>', html, re.S):
        name, body = m.group(1), m.group(2)
        stroke, duo, dots = [], [], False
        for tag in re.findall(r"<(?:path|circle|rect)\b[^>]*/?>", body):
            d = to_wpf(shape_to_path(tag))
            style = attr(tag, "style", "")
            if "stroke-width:3" in style:
                dots = True
            if "fill:var(--duo" in style:
                duo.append(d)
            if "stroke:none" not in style:
                stroke.append(d)
        rows.append((pascal(name), " ".join(stroke), " ".join(duo), dots))
    out = [
        "// <auto-generated> by tools/icons/convert-icons.py from the direction A icon symbols. Do not edit by hand. </auto-generated>",
        "namespace Lifestream.Desktop.Controls;",
        "",
        "/// <summary>The outline icon set of direction A: 24 x 24 path data, drawn with a 1.5 px round stroke; Duo is the area filled in the selected state.</summary>",
        "internal static class IconData",
        "{",
        "    public static readonly IReadOnlyDictionary<IconKind, (string Stroke, string Duo, bool Dots)> All = new Dictionary<IconKind, (string, string, bool)>",
        "    {",
    ]
    for name, stroke, duo, dots in rows:
        out.append(f'        [IconKind.{name}] = ("{stroke}", "{duo}", {str(dots).lower()}),')
    out += ["    };", "}", "", "/// <summary>Every icon of the set (Controls/Icon).</summary>", "public enum IconKind", "{", "    None,"]
    out += [f"    {name}," for name, *_ in rows]
    out += ["}", ""]
    sys.stdout.write("\n".join(out))


if __name__ == "__main__":
    main(sys.argv[1])
